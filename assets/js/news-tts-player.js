  function getLanguage() {
    const path = window.location.pathname.toLowerCase();
    const htmlLang = (
      document.documentElement.lang || ""
    ).toLowerCase();

    if (
      path.includes("/zh-cn/") ||
      htmlLang.startsWith("zh")
    ) {
      return "zh-CN";
    }

    if (
      path.includes("/it/") ||
      htmlLang.startsWith("it")
    ) {
      return "it";
    }

    return "en";
  }

  function getArticleId() {
    const params = new URLSearchParams(
      window.location.search
    );

    return (
      params.get("article") ||
      params.get("id") ||
      params.get("news")
    );
  }

  function getNewsArray(data) {
    if (Array.isArray(data)) {
      return data;
    }

    if (Array.isArray(data?.news)) {
      return data.news;
    }

    return [];
  }

  function findArticle(data, articleId) {
    return getNewsArray(data).find(
      (item) =>
        item &&
        (
          item.id === articleId ||
          item.slug === articleId
        )
    );
  }

  function resolveAudio(article, lang) {
    const audio = article?.audio;

    if (!audio) {
      return null;
    }

    if (typeof audio === "string") {
      return {
        src: audio,
        type: "audio/mpeg",
      };
    }

    const candidates = [
      lang,
      lang.toLowerCase(),
      lang.split("-")[0],
      "en",
      "zh-CN",
      "it",
    ];

    for (const key of candidates) {
      const value = audio[key];

      if (typeof value === "string") {
        return {
          src: value,
          type: "audio/mpeg",
        };
      }

      if (
        value &&
        typeof value === "object" &&
        typeof value.src === "string"
      ) {
        return value;
      }
    }

    return null;
  }

  function formatTime(seconds) {
    if (!Number.isFinite(seconds) || seconds < 0) {
      return "0:00";
    }

    const minutes = Math.floor(seconds / 60);
    const remaining = Math.floor(seconds % 60);

    return `${minutes}:${String(remaining).padStart(2, "0")}`;
  }

